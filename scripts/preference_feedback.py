"""Ingest trusted-owner issue feedback and retrain without downloading images."""
import argparse
import json
import os
import re
from datetime import datetime
from pathlib import Path
from abyss.feedback import normalize, parse_body
from abyss.preferences import train
from abyss.evaluation import prospective_report
from abyss.publication import atomic_json


def ingest(state, event, reviewer, actor):
    issue = event['issue']
    if issue['user']['login'] != reviewer or actor != reviewer:
        raise ValueError('Only the configured reviewer can submit preference feedback')
    if not issue['title'].startswith('Abyss preferences'):
        raise ValueError('Not an Abyss preference issue')
    payload = parse_body(issue.get('body') or '')
    manifest_path = Path(state) / 'batches' / (payload['batch_id'] + '.json')
    if not manifest_path.exists():
        raise ValueError('Unknown review batch; use a gallery generated by this repository')
    manifest = json.loads(manifest_path.read_text())
    updated = issue['updated_at']
    if datetime.fromisoformat(updated.replace('Z', '+00:00')).tzinfo is None:
        raise ValueError('Issue update time must include timezone')
    normalized = normalize(payload, manifest, reviewer=reviewer,
                           issue_number=issue['number'], updated_at=updated)
    atomic_json(Path(state) / 'feedback' / f'issue-{int(issue["number"])}.json', normalized)
    return normalized


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--state', default='/tmp/preference-state')
    parser.add_argument('--reviewer', default=os.environ.get('PREFERENCE_REVIEWER'))
    parser.add_argument('--event')
    args = parser.parse_args()
    if not args.reviewer or not re.fullmatch('[A-Za-z0-9][A-Za-z0-9-]{0,38}', args.reviewer):
        parser.error('Set the configured GitHub reviewer')
    if args.event:
        ingest(args.state, json.loads(Path(args.event).read_text()), args.reviewer, os.environ.get('GITHUB_ACTOR'))
    documents = [json.loads(p.read_text()) for p in sorted((Path(args.state) / 'feedback').glob('*.json'))]
    model = train(documents, args.reviewer)
    manifests = {p.stem: json.loads(p.read_text()) for p in (Path(args.state) / 'batches').glob('*.json')}
    model['prospective_evaluation'] = prospective_report(documents, manifests, args.reviewer)
    atomic_json(Path(args.state) / 'model.json', model)
    atomic_json(Path(args.state) / 'training-report.json', {k: v for k, v in model.items() if k != 'weights'})
    print(json.dumps({k: model[k] for k in ('status', 'reviewer', 'comparisons', 'pairwise_comparisons', 'evaluation', 'prospective_evaluation', 'model_id')}, indent=2))


if __name__ == '__main__': main()
